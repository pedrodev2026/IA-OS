#![no_std]
#![no_main]

use core::arch::asm;
use core::panic::PanicInfo;

#[used]
#[link_section = ".requests"]
static FRAMEBUFFER_REQUEST: limine::request::FramebufferRequest =
    limine::request::FramebufferRequest::new();

#[no_mangle]
pub extern "C" fn _start() -> ! {
    if let Some(fb_response) = FRAMEBUFFER_REQUEST.response() {
        if let Some(framebuffer) = fb_response.framebuffers().first() {
            let width = framebuffer.width as usize;
            let height = framebuffer.height as usize;
            let pitch = framebuffer.pitch as usize;
            let bpp = framebuffer.bpp as usize;
            let fb_ptr = framebuffer.address() as *mut u8;

            // Preenche o fundo com azul escuro (0x00101826)
            let bg_color: u32 = 0x00101826;
            for y in 0..height {
                for x in 0..width {
                    put_pixel(fb_ptr, pitch, bpp, x, y, bg_color);
                }
            }

            // Desenha uma moldura decorativa na tela
            let border_color: u32 = 0x0000D2FF;
            for x in 20..(width.saturating_sub(20)) {
                put_pixel(fb_ptr, pitch, bpp, x, 20, border_color);
                put_pixel(fb_ptr, pitch, bpp, x, 21, border_color);
                put_pixel(fb_ptr, pitch, bpp, x, height.saturating_sub(21), border_color);
                put_pixel(fb_ptr, pitch, bpp, x, height.saturating_sub(20), border_color);
            }
            for y in 20..(height.saturating_sub(20)) {
                put_pixel(fb_ptr, pitch, bpp, 20, y, border_color);
                put_pixel(fb_ptr, pitch, bpp, 21, y, border_color);
                put_pixel(fb_ptr, pitch, bpp, width.saturating_sub(21), y, border_color);
                put_pixel(fb_ptr, pitch, bpp, width.saturating_sub(20), y, border_color);
            }

            // Exibe o texto de inicialização: "IA-OS v0.1.0-alpha.1"
            let text = "IA-OS v0.1.0-alpha.1";
            let text_color: u32 = 0x0000FF99;
            draw_string_scale2(fb_ptr, pitch, bpp, 40, 50, text, text_color);

            let subtext = "Kernel x86_64 inicializado com sucesso via Limine (UEFI)!";
            let subtext_color: u32 = 0x00E0E6ED;
            draw_string(fb_ptr, pitch, bpp, 40, 90, subtext, subtext_color);

            let status_text = "[OK] Framebuffer linear ativo | Modo Longo (Ring 0)";
            let status_color: u32 = 0x00FFD166;
            draw_string(fb_ptr, pitch, bpp, 40, 115, status_text, status_color);
        }
    }

    hcf();
}

#[inline(always)]
fn put_pixel(fb_ptr: *mut u8, pitch: usize, bpp: usize, x: usize, y: usize, color: u32) {
    if bpp == 32 {
        let offset = y * pitch + x * 4;
        unsafe {
            let pixel_ptr = fb_ptr.add(offset) as *mut u32;
            pixel_ptr.write_volatile(color);
        }
    }
}

fn draw_string(fb_ptr: *mut u8, pitch: usize, bpp: usize, start_x: usize, start_y: usize, s: &str, color: u32) {
    let mut current_x = start_x;
    for b in s.bytes() {
        draw_char(fb_ptr, pitch, bpp, current_x, start_y, b, color);
        current_x += 9;
    }
}

fn draw_string_scale2(fb_ptr: *mut u8, pitch: usize, bpp: usize, start_x: usize, start_y: usize, s: &str, color: u32) {
    let mut current_x = start_x;
    for b in s.bytes() {
        draw_char_scale2(fb_ptr, pitch, bpp, current_x, start_y, b, color);
        current_x += 18;
    }
}

fn draw_char(fb_ptr: *mut u8, pitch: usize, bpp: usize, x: usize, y: usize, c: u8, color: u32) {
    let glyph = get_glyph(c);
    for row in 0..16 {
        let byte = glyph[row];
        for col in 0..8 {
            if (byte & (0x80 >> col)) != 0 {
                put_pixel(fb_ptr, pitch, bpp, x + col, y + row, color);
            }
        }
    }
}

fn draw_char_scale2(fb_ptr: *mut u8, pitch: usize, bpp: usize, x: usize, y: usize, c: u8, color: u32) {
    let glyph = get_glyph(c);
    for row in 0..16 {
        let byte = glyph[row];
        for col in 0..8 {
            if (byte & (0x80 >> col)) != 0 {
                let px = x + col * 2;
                let py = y + row * 2;
                put_pixel(fb_ptr, pitch, bpp, px, py, color);
                put_pixel(fb_ptr, pitch, bpp, px + 1, py, color);
                put_pixel(fb_ptr, pitch, bpp, px, py + 1, color);
                put_pixel(fb_ptr, pitch, bpp, px + 1, py + 1, color);
            }
        }
    }
}

